/** Central ES/EN dictionary. `en` must match the shape of `es` (type-checked). */

export type Lang = 'es' | 'en';

export function langFromPath(pathname: string): Lang {
  return pathname === '/en' || pathname.startsWith('/en/') ? 'en' : 'es';
}

/** Language prefix for internal links: '' for ES, '/en' for EN. */
export function prefix(lang: Lang): string {
  return lang === 'en' ? '/en' : '';
}

/** Counterpart URL of the current page in the other language. */
export function counterpart(pathname: string, search: string, lang: Lang): string {
  const other: Lang = lang === 'en' ? 'es' : 'en';
  let path = pathname;
  if (other === 'en') {
    path = pathname === '/' ? '/en/' : `/en${pathname}`;
  } else {
    path = pathname === '/en' || pathname === '/en/' ? '/' : pathname.replace(/^\/en/, '') || '/';
  }
  return `${path}${search}`;
}

export function docLang(): Lang {
  if (typeof document === 'undefined') return 'es';
  return document.documentElement.lang === 'en' ? 'en' : 'es';
}

